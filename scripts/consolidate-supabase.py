"""MS-35 / SDD-C12 / QAD-TC35: generate clean-install SQL from preserved history.

No database connection is opened. Historical data repairs remain in the archive.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
DB = ROOT / 'supabase'
ARCHIVE = DB / 'archive' / 'pre-consolidation'


def split_sql(text, delimiter=';'):
    """Split outside quoted strings, comments, dollar bodies, and parentheses."""
    result, buf, i, depth = [], [], 0, 0
    while i < len(text):
        if text.startswith('--', i):
            end = text.find('\n', i)
            i = len(text) if end < 0 else end
            buf.append('\n')
            continue
        if text.startswith('/*', i):
            end = text.index('*/', i + 2)
            i = end + 2
            buf.append(' ')
            continue
        ch = text[i]
        dollar = re.match(r'\$(?:[A-Za-z_][A-Za-z_0-9]*)?\$', text[i:]) if ch == '$' else None
        if dollar:
            tag = dollar.group()
            end = text.index(tag, i + len(tag)) + len(tag)
            buf.append(text[i:end])
            i = end
            continue
        if ch in "'\"":
            end = i + 1
            while end < len(text):
                if text[end] == ch:
                    if end + 1 < len(text) and text[end + 1] == ch:
                        end += 2
                        continue
                    end += 1
                    break
                end += 1
            buf.append(text[i:end])
            i = end
            continue
        if ch == '(':
            depth += 1
        elif ch == ')':
            depth -= 1
        if ch == delimiter and depth == 0:
            statement = ''.join(buf).strip()
            if statement:
                result.append(statement)
            buf = []
        else:
            buf.append(ch)
        i += 1
    if ''.join(buf).strip():
        result.append(''.join(buf).strip())
    return result


def emit(name, title, statements, transaction=True):
    body = '\n\n'.join(s.strip().rstrip(';') + ';' for s in statements)
    if name != '002_functions.sql':
        body = '\n'.join(line.rstrip() for line in body.split('\n'))
    header = f'-- DeskAtlas: {title}\n-- Traceability: MS-35, SDD-C1, SDD-C3, SDD-C12, ERD-E1 through ERD-E14, QAD-TC35.\n-- Generated by scripts/consolidate-supabase.py from archive/pre-consolidation.\n'
    (DB / name).write_text(header + ('\nBEGIN;\n\n' if transaction else '\n') + body + ('\n\nCOMMIT;\n' if transaction else '\n'), encoding='utf-8')


def generate():
    tables, types, functions, indexes = {}, {}, {}, {}
    extensions, triggers, security, comments, realtime = [], [], [], [], []
    removed_indexes = {'idx_reservation_candidates_availability', 'idx_reservation_candidates_reservation_id', 'idx_reservations_reference_code'}

    def alter(statement):
        match = re.match(r'ALTER TABLE (?:public\.)?(\w+)\s+(.*)', statement, re.S)
        assert match, statement
        name, actions = match.groups()
        for action in split_sql(actions, ','):
            column = re.match(r'ADD COLUMN IF NOT EXISTS (\w+)\s+(.*)', action, re.S | re.I)
            if column:
                key, definition = column.groups()
                if not any(re.match(rf'{key}\s', item, re.I) for item in tables[name]):
                    tables[name].append(f'{key} {definition}')
            elif re.match(r'DROP CONSTRAINT', action, re.I):
                key = action.split()[-1]
                tables[name] = [item for item in tables[name] if not re.match(rf'CONSTRAINT\s+{key}\b', item, re.I)]
            elif re.match(r'ADD CONSTRAINT', action, re.I):
                definition = action[4:]
                key = definition.split()[1]
                if not any(re.match(rf'CONSTRAINT\s+{key}\b', item, re.I) for item in tables[name]):
                    tables[name].append(definition)
            else:
                raise ValueError(f'Unclassified schema action: {action}')

    for file in sorted(ARCHIVE.glob('[0-9][0-9][0-9]_*.sql')):
        if file.name.startswith(('000_', '003_')):
            continue
        for s in split_sql(file.read_text(encoding='utf-8-sig')):
            if s in ('BEGIN', 'COMMIT'):
                continue
            if re.match(r'CREATE (?:OR REPLACE )?FUNCTION', s):
                key = re.match(r'CREATE (?:OR REPLACE )?FUNCTION\s+(\S+)\s*\(', s).group(1)
                functions[key] = s
            elif re.match(r'CREATE TABLE', s):
                m = re.match(r'CREATE TABLE (?:IF NOT EXISTS )?public\.(\w+)\s*\((.*)\)$', s, re.S)
                assert m, s
                tables[m[1]] = split_sql(m[2], ',')
            elif s.startswith('CREATE TYPE'):
                key = re.match(r'CREATE TYPE public\.(\w+)', s)[1]
                types[key] = s
            elif s.startswith('CREATE EXTENSION'):
                extensions.append(s)
            elif re.match(r'CREATE (?:UNIQUE )?INDEX', s):
                s = s.replace(' CONCURRENTLY', '')
                key = re.match(r'CREATE (?:UNIQUE )?INDEX (?:IF NOT EXISTS )?(\w+)', s)[1]
                if key not in removed_indexes:
                    indexes.setdefault(key, s)
            elif re.match(r'CREATE (?:CONSTRAINT )?TRIGGER', s):
                triggers.append(s)
            elif file.name.startswith(('013_', '024_')):
                realtime.append(s)
            elif re.match(r'(GRANT|REVOKE|ALTER DEFAULT PRIVILEGES|CREATE POLICY|DROP POLICY)', s) or 'ENABLE ROW LEVEL SECURITY' in s:
                security.append(s)
            elif s.startswith('COMMENT ON'):
                comments.append(s)
            elif file.name.startswith('022_'):
                continue  # Proven duplicate indexes are not created in a clean install.
            elif s.startswith('DO'):
                if 'ALTER TYPE' in s:
                    types['pricing_unit'] = "CREATE TYPE public.pricing_unit AS ENUM ('HOURLY', 'DAY_PASS', 'NIGHT_PASS')"
                elif 'to_regprocedure' in s:
                    security.append(s)  # Verify the final function catalog and privileges.
                elif file.name.startswith('014_'):
                    continue  # Existing-data compiled-map backfill is preserved in the archive.
                elif file.name.startswith('011_') and any('workspace_instances_template_display_name_unique' in item for item in tables['workspace_instances']):
                    continue  # The historical guard accepts either constraint identity.
                else:
                    alterations = re.findall(r'ALTER TABLE\s+(?:public\.)?\w+\s+ADD CONSTRAINT.*?;', s, re.S)
                    assert alterations, f'Unclassified DO block in {file.name}'
                    for item in alterations:
                        alter(item.rstrip(';'))
            elif s.startswith('ALTER TABLE'):
                if ' TRIGGER ' not in s:
                    alter(s)
            elif re.match(r'(UPDATE|WITH)\b', s):
                continue  # Existing-data repair, not seed or clean-install schema.
            else:
                raise ValueError(f'Unclassified statement in {file.name}: {s[:100]}')

    # MS-81: reviewed forward replacements override history for clean installs.
    # Read only the replacement tags, never execute guarded migration/down SQL.
    repair = (DB / 'migrations/041_staff_rpc_ambiguity.sql').read_text(encoding='utf-8')
    for definition in re.findall(r'EXECUTE \$ms81_replacement\$([\s\S]*?)\$ms81_replacement\$;', repair):
        key = re.match(r'CREATE OR REPLACE FUNCTION\s+(\S+)\s*\(', definition).group(1)
        if key not in functions:
            raise ValueError(f'MS81 unknown function: {key}')
        functions[key] = definition.rstrip(';')

    # The reservation-reference default depends on a function installed in 002.
    tables['reservations'] = [item.replace(' DEFAULT public.generate_reservation_reference()', '') for item in tables['reservations']]
    creates = [f'CREATE TABLE public.{name} (\n  ' + ',\n  '.join(items) + '\n)' for name, items in tables.items()]
    emit('001_schema.sql', 'Enums, tables, constraints, indexes, and column comments', extensions + list(types.values()) + creates + list(indexes.values()) + comments)
    emit('002_functions.sql', 'Latest functions, reservation default, and integrity triggers', list(functions.values()) + ['ALTER TABLE public.reservations ALTER COLUMN reference_code SET DEFAULT public.generate_reservation_reference()'] + triggers)
    # Preserve grant/revoke ordering: broad grants precede the historical final RPC restrictions.
    emit('004_security_and_rls.sql', 'Permissions and row level security', security)
    emit('005_realtime.sql', 'Operational and reference-data Realtime publication', realtime)

    # DrawSQL receives only type/table/relationship DDL, including an auth.users stub.
    # Functions, triggers, policies, and extensions belong to deployment SQL.
    draw_tables = []
    foreign_keys = []
    for name, items in tables.items():
        columns = []
        for item in items:
            if re.match(r'CONSTRAINT\b', item, re.I):
                if re.search(r'\bFOREIGN KEY\b', item, re.I):
                    foreign_keys.append(f'ALTER TABLE {name} ADD {item}')
                else:
                    columns.append(item)
                continue
            if name == 'reservations' and item.startswith('reference_code '):
                item += ' DEFAULT generate_reservation_reference()'
            ref = re.search(r'\s+REFERENCES\s+(.+)$', item, re.S | re.I)
            if ref:
                foreign_keys.append(f'ALTER TABLE {name} ADD FOREIGN KEY ({item.split()[0]}) REFERENCES {ref[1]}')
                item = item[:ref.start()]
            columns.append(item)
        draw_tables.append(f'CREATE TABLE {name} (\n  ' + ',\n  '.join(columns) + '\n)')
    ddl = ['CREATE TABLE users (id uuid PRIMARY KEY)'] + list(types.values()) + draw_tables + foreign_keys + list(indexes.values()) + comments
    ddl = [s.replace('public.', '').replace('auth.users', 'users') for s in ddl]
    emit('sql_schema.sql', 'DrawSQL import: all current tables and foreign keys; users represents auth.users', ddl, False)
    print(f'Generated {len(tables)} application tables, {len(functions)} functions, {len(triggers)} triggers, {len(indexes)} indexes, {len(foreign_keys)} foreign keys.')


if __name__ == '__main__':
    generate()
